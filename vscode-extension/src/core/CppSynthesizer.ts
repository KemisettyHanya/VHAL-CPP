import { CanMessage, CanSignal, Endianness, NodeLink, UnitConversion, VhalPropertyType } from "./AutomotiveTypes";
import { VhalCatalog } from "./VhalCatalog";

export class CppSynthesizer {
    public synthesize(links: NodeLink[], dbcMessages: CanMessage[] = []): string {
        const out: string[] = [];
        const timestamp = new Date().toISOString();

        // 1. Header Banner
        out.push("/*******************************************************************************");
        out.push(" * AUTO-GENERATED VEHICLE HARDWARE ABSTRACTION LAYER (VHAL) ADAPTER");
        out.push(" * Generated by: CAN-to-AOSP VHAL Mapping Studio (VS Code Extension)");
        out.push(` * Timestamp:    ${timestamp}`);
        out.push(" * Specification: Android Automotive OS (AOSP) AIDL IVehicle Interface");
        out.push(" * Standard:      MISRA-C++:2008 & Modern C++20 Compliant");
        out.push(" ******************************************************************************/");
        out.push("");

        // 2. Metadata Block (for 100% lossless visual studio reloading)
        out.push("// CAN_VHAL_STUDIO_METADATA_START");
        for (const link of links) {
            let meta = `// LINK: CAN_ID=0x${link.canMsgId.toString(16).toUpperCase()} CAN_NAME=${link.canMsgName} SIGNAL=${link.signalName} PROP_ID=0x${link.vhalPropertyId.toString(16).toUpperCase()} PROP_NAME=${link.vhalPropertyName}`;
            meta += ` CONV=${link.transform.conversion} SCALE=${link.transform.customScale} OFFSET=${link.transform.customOffset}`;
            meta += ` CLAMP=${link.transform.hasClamp ? 1 : 0} MIN=${link.transform.clampMin} MAX=${link.transform.clampMax}`;
            meta += ` AREA=${link.transform.areaId}`;
            if (link.transform.customExpression) {
                meta += ` EXPR=${encodeURIComponent(link.transform.customExpression)}`;
            }
            out.push(meta);
        }
        out.push("// CAN_VHAL_STUDIO_METADATA_END");
        out.push("");

        // 3. Includes
        out.push("#include <cstdint>");
        out.push("#include <vector>");
        out.push("#include <string>");
        out.push("#include <algorithm>");
        out.push("#include <chrono>");
        out.push("#include <functional>");
        out.push("#include <linux/can.h>");
        out.push("#include <aidl/android/hardware/automotive/vehicle/VehiclePropValue.h>");
        out.push("#include <aidl/android/hardware/automotive/vehicle/VehicleProperty.h>");
        out.push("");
        out.push("using aidl::android::hardware::automotive::vehicle::VehiclePropValue;");
        out.push("using aidl::android::hardware::automotive::vehicle::VehicleProperty;");
        out.push("");

        // 4. Function Definition
        out.push("/**");
        out.push(" * @brief Dispatches raw incoming CAN frames to AOSP VehiclePropValue callbacks.");
        out.push(" * @param frame Raw CAN 2.0B / CAN-FD Linux socketcan frame.");
        out.push(" * @param dispatchCallback Callback receiving synthesized Android VehiclePropValues.");
        out.push(" */");
        out.push("void onCanFrameReceived(");
        out.push("    const struct can_frame& frame,");
        out.push("    const std::function<void(const std::vector<VehiclePropValue>&)>& dispatchCallback) {");
        out.push("");
        out.push("    const int64_t timestampNs = std::chrono::duration_cast<std::chrono::nanoseconds>(");
        out.push("        std::chrono::system_clock::now().time_since_epoch()).count();");
        out.push("");
        out.push("    std::vector<VehiclePropValue> dispatchedProps;");
        out.push("    dispatchedProps.reserve(4);");
        out.push("");
        out.push("    switch (frame.can_id) {");

        // Group links by CAN Message ID
        const grouped = new Map<number, NodeLink[]>();
        for (const l of links) {
            if (!grouped.has(l.canMsgId)) grouped.set(l.canMsgId, []);
            grouped.get(l.canMsgId)!.push(l);
        }

        const catalog = VhalCatalog.getInstance();

        for (const [msgId, msgLinks] of grouped) {
            const hexId = "0x" + msgId.toString(16).toUpperCase();
            out.push(`        case ${hexId}: { // ${msgLinks[0].canMsgName}`);

            // Find message in DBC if available
            const dbcMsg = dbcMessages.find(m => m.id === msgId);

            for (const link of msgLinks) {
                out.push(`            // --- Mapping: [${link.signalName}] -> ${link.vhalPropertyName} ---`);

                // Find signal in DBC
                let sig: CanSignal | undefined;
                if (dbcMsg) {
                    sig = dbcMsg.signals.find(s => s.name === link.signalName);
                }

                if (!sig) {
                    // Default fallback signal parameters
                    sig = {
                        name: link.signalName,
                        startBit: 0,
                        bitLength: 16,
                        endianness: Endianness.LittleEndian,
                        signedVal: false,
                        factor: 1.0,
                        offset: 0.0,
                        minVal: 0,
                        maxVal: 65535,
                        unit: "",
                        receiver: "",
                        valueDescriptions: []
                    };
                }

                // Bit extraction
                if (sig.endianness === Endianness.LittleEndian) {
                    if (sig.startBit % 8 === 0 && sig.bitLength === 8) {
                        const byteIdx = Math.floor(sig.startBit / 8);
                        out.push(`            const uint8_t raw_${sig.name} = frame.data[${byteIdx}];`);
                    } else if (sig.startBit % 8 === 0 && sig.bitLength === 16) {
                        const b0 = Math.floor(sig.startBit / 8);
                        const b1 = b0 + 1;
                        out.push(`            const uint16_t raw_${sig.name} = static_cast<uint16_t>(frame.data[${b0}]) | (static_cast<uint16_t>(frame.data[${b1}]) << 8);`);
                    } else if (sig.startBit % 8 === 0 && sig.bitLength === 32) {
                        const b0 = Math.floor(sig.startBit / 8);
                        out.push(`            const uint32_t raw_${sig.name} = static_cast<uint32_t>(frame.data[${b0}]) | (static_cast<uint32_t>(frame.data[${b0 + 1}]) << 8) | (static_cast<uint32_t>(frame.data[${b0 + 2}]) << 16) | (static_cast<uint32_t>(frame.data[${b0 + 3}]) << 24);`);
                    } else {
                        const bIdx = Math.floor(sig.startBit / 8);
                        const shift = sig.startBit % 8;
                        const mask = ((1 << sig.bitLength) - 1);
                        out.push(`            const uint32_t raw_${sig.name} = (frame.data[${bIdx}] >> ${shift}) & 0x${mask.toString(16).toUpperCase()};`);
                    }
                } else {
                    // Big Endian (Motorola)
                    if (sig.bitLength === 16 && sig.startBit % 8 === 7) {
                        const b0 = Math.floor(sig.startBit / 8);
                        const b1 = b0 + 1;
                        out.push(`            const uint16_t raw_${sig.name} = (static_cast<uint16_t>(frame.data[${b0}]) << 8) | static_cast<uint16_t>(frame.data[${b1}]);`);
                    } else {
                        const bIdx = Math.floor(sig.startBit / 8);
                        out.push(`            const uint32_t raw_${sig.name} = frame.data[${bIdx}];`);
                    }
                }

                // Signedness handling
                let valExpr = `raw_${sig.name}`;
                if (sig.signedVal) {
                    out.push(`            const int32_t signed_${sig.name} = (raw_${sig.name} ^ (1U << ${sig.bitLength - 1})) - (1U << ${sig.bitLength - 1});`);
                    valExpr = `signed_${sig.name}`;
                }

                // Physical Scaling
                let physExpr = `(static_cast<float>(${valExpr}) * ${sig.factor}f + ${sig.offset}f)`;
                if (sig.factor === 1.0 && sig.offset === 0.0) {
                    physExpr = `static_cast<float>(${valExpr})`;
                }

                // Conversion
                let finalExpr = physExpr;
                switch (link.transform.conversion) {
                    case UnitConversion.KMH_TO_MPS:
                        finalExpr = `(${physExpr} / 3.6f)`;
                        break;
                    case UnitConversion.MPS_TO_KMH:
                        finalExpr = `(${physExpr} * 3.6f)`;
                        break;
                    case UnitConversion.CELSIUS_TO_KELVIN:
                        finalExpr = `(${physExpr} + 273.15f)`;
                        break;
                    case UnitConversion.KELVIN_TO_CELSIUS:
                        finalExpr = `(${physExpr} - 273.15f)`;
                        break;
                    case UnitConversion.RPM_TO_RADS:
                        finalExpr = `(${physExpr} * 0.10472f)`;
                        break;
                    case UnitConversion.CUSTOM_EXPR:
                        if (link.transform.customExpression) {
                            finalExpr = `(${link.transform.customExpression.replace(/rawVal/g, physExpr)})`;
                        }
                        break;
                    default:
                        break;
                }

                // Clamping
                if (link.transform.hasClamp) {
                    finalExpr = `std::clamp(${finalExpr}, ${link.transform.clampMin}f, ${link.transform.clampMax}f)`;
                }

                // Target Property Type packaging
                const vhalProp = catalog.findById(link.vhalPropertyId);
                const propType = vhalProp ? vhalProp.type : VhalPropertyType.FLOAT;

                out.push(`            float val_${sig.name} = ${finalExpr};`);
                out.push(`            VehiclePropValue prop_${sig.name};`);
                out.push(`            prop_${sig.name}.prop = static_cast<int32_t>(VehicleProperty::${link.vhalPropertyName});`);
                out.push(`            prop_${sig.name}.areaId = ${link.transform.areaId};`);
                out.push(`            prop_${sig.name}.timestamp = timestampNs;`);

                if (propType === VhalPropertyType.BOOLEAN) {
                    out.push(`            prop_${sig.name}.value.int32Values.push_back(val_${sig.name} > 0.5f ? 1 : 0);`);
                } else if (propType === VhalPropertyType.INT32) {
                    out.push(`            prop_${sig.name}.value.int32Values.push_back(static_cast<int32_t>(val_${sig.name}));`);
                } else {
                    out.push(`            prop_${sig.name}.value.floatValues.push_back(val_${sig.name});`);
                }
                out.push(`            dispatchedProps.push_back(std::move(prop_${sig.name}));`);
                out.push("");
            }

            out.push("            break;");
            out.push("        }");
        }

        out.push("        default:");
        out.push("            break;");
        out.push("    }");
        out.push("");
        out.push("    if (!dispatchedProps.empty() && dispatchCallback) {");
        out.push("        dispatchCallback(dispatchedProps);");
        out.push("    }");
        out.push("}");
        out.push("");

        return out.join("\n");
    }
}

